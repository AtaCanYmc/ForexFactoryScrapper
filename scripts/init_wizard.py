#!/usr/bin/env python3
"""Interactive setup: asks for each setting and writes a .env file.

Usage:
    python scripts/init_wizard.py              # prompt for every value
    python scripts/init_wizard.py --defaults   # write defaults, no prompts
    python scripts/init_wizard.py --output path/to/.env
"""

import argparse
import os
import sys

# (key, prompt, default, type) where type is "int", "bool", "choice:a|b" or "str".
SETTINGS = [
    (
        "HOST",
        "Bind address (127.0.0.1 local only, 0.0.0.0 containers)",
        "127.0.0.1",
        "str",
    ),
    ("PORT", "Port", "5000", "int"),
    ("DEBUG", "Debug mode (never True in production)", "False", "bool"),
    ("CORS_ORIGINS", "Allowed CORS origins, comma-separated or *", "*", "str"),
    ("MAX_BUNDLE_DAYS", "Max days per /api/bundle request", "31", "int"),
    ("MAX_SITEMAP_PAGES", "Max sitemap pages to crawl", "100", "int"),
    ("CACHE_TTL_SECONDS", "Upstream cache TTL in seconds (0 = off)", "0", "int"),
    ("CACHE_MAX_ENTRIES", "Max cached upstream responses", "256", "int"),
    ("RATE_LIMIT_PER_MINUTE", "Requests per minute per client (0 = off)", "0", "int"),
    ("LOG_FORMAT", "Log format", "text", "choice:text|json"),
    ("LOG_LEVEL", "Log level", "INFO", "choice:DEBUG|INFO|WARNING|ERROR"),
    (
        "TRUST_PROXY_HOPS",
        "Trusted reverse-proxy hops (0 if exposed directly)",
        "0",
        "int",
    ),
]


def normalize(value, kind):
    """Return the cleaned value, or None if it is invalid for this type."""
    value = value.strip()
    if kind == "int":
        return str(int(value)) if value.isdigit() else None
    if kind == "bool":
        v = value.lower()
        return {
            "true": "True",
            "yes": "True",
            "y": "True",
            "1": "True",
            "false": "False",
            "no": "False",
            "n": "False",
            "0": "False",
        }.get(v)
    if kind.startswith("choice:"):
        for opt in kind[7:].split("|"):
            if opt.lower() == value.lower():
                return opt
        return None
    return value or None


def build_env(answers):
    return "# Generated by scripts/init_wizard.py\n" + "".join(
        f"{k}={answers[k]}\n" for k, *_ in SETTINGS
    )


def ask(key, prompt, default, kind):
    while True:
        raw = input(f"{prompt} [{default}]: ").strip() or default
        value = normalize(raw, kind)
        if value is not None:
            return value
        print(f"  Invalid value for {key}. Expected {kind.replace('choice:', '')}.")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--defaults", action="store_true", help="skip prompts")
    ap.add_argument("--output", default=".env", help="file to write (default .env)")
    args = ap.parse_args(argv)

    if os.path.exists(args.output) and not args.defaults:
        if input(f"{args.output} exists. Overwrite? [y/N]: ").strip().lower() != "y":
            print("Aborted.")
            return 1
    elif os.path.exists(args.output):
        print(
            f"{args.output} exists. Refusing to overwrite with --defaults.",
            file=sys.stderr,
        )
        return 1

    answers = {
        key: default if args.defaults else ask(key, prompt, default, kind)
        for key, prompt, default, kind in SETTINGS
    }
    with open(args.output, "w", encoding="utf-8") as f:
        f.write(build_env(answers))
    print(f"Wrote {args.output}. Start the API with: python main.py")
    return 0


if __name__ == "__main__":
    sys.exit(main())
